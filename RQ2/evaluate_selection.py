#!/usr/bin/env python3
"""
RQ2: Evaluation of Selection Algorithms for LLM4Decompile

This script evaluates different selection strategies for choosing the best
decompiled candidate from multiple samples generated by LLM4Decompile.

Metrics evaluated:
- Pass@1 (functional correctness)
- Levenshtein similarity (edit distance to original)
- CodeBLEU (code-aware BLEU score)

Selection strategies evaluated:
- Random selection (baseline)
- Text-based metrics (edit_similarity, token_f1, bigram_sim, trigram_sim)
- AST-based metrics (ast_node_sim, control_flow_sim, identifier_sim)
- Embedding-based (UniXcoder base, UniXcoder finetuned)
- Perplexity-based (neg_perplexity)
- Ensemble methods
"""

import os
import sys
import json
import pickle
import random
from dataclasses import dataclass, field
from typing import List, Dict, Tuple, Optional
from pathlib import Path
from tqdm import tqdm

import Levenshtein
from codebleu import calc_codebleu

# Configuration
CACHE_DIR = Path("./cache")
NUM_SAMPLES = 656
NUM_CANDIDATES = 100
RANDOM_SEED = 42
SEED: Optional[int] = 42


@dataclass
class Candidate:
    """A decompiled code candidate."""
    code: str
    temperature: float
    compiles: bool = False
    passes_tests: bool = False
    metrics: Dict[str, float] = field(default_factory=dict)


@dataclass
class Sample:
    """A sample with multiple candidates."""
    idx: int
    opt: str
    ghidra: str
    c_func: str
    c_test: str
    candidates: List[Candidate] = field(default_factory=list)


@dataclass
class SelectionResult:
    """Results for a selection strategy."""
    correct: int = 0
    total: int = 0
    levenshtein_sum: float = 0.0
    codebleu_sum: float = 0.0
    count: int = 0


def seed_suffix(seed: Optional[int]) -> str:
    return "" if seed is None else f"_seed{seed}"


def resolve_cache_file(cache_dir: Path, base_name: str, suffix: str, seed: Optional[int], required: bool = False) -> Path:
    preferred = cache_dir / f"{base_name}{seed_suffix(seed)}{suffix}"
    legacy = cache_dir / f"{base_name}{suffix}"

    if preferred.exists():
        return preferred
    if legacy.exists():
        return legacy

    matches = sorted(cache_dir.glob(f"{base_name}*{suffix}"))
    if len(matches) == 1:
        return matches[0]

    if seed is None:
        seed_matches = sorted(cache_dir.glob(f"{base_name}_seed*{suffix}"))
        if len(seed_matches) == 1:
            return seed_matches[0]

    if required:
        return preferred
    return preferred


def compute_levenshtein_similarity(s1: str, s2: str) -> float:
    """Compute normalized Levenshtein similarity (1 - normalized distance)."""
    if not s1 and not s2:
        return 1.0
    if not s1 or not s2:
        return 0.0
    distance = Levenshtein.distance(s1, s2)
    max_len = max(len(s1), len(s2))
    return 1.0 - (distance / max_len)


def compute_codebleu(reference: str, candidate: str) -> float:
    """Compute CodeBLEU score for code comparison."""
    try:
        if not reference.strip() or not candidate.strip():
            return 0.0
        result = calc_codebleu(
            references=[[reference]],
            predictions=[candidate],
            lang="c",
            weights=(0.25, 0.25, 0.25, 0.25),
            tokenizer=None
        )
        return result['codebleu']
    except Exception as e:
        return 0.0


def extract_function_body(code: str) -> str:
    """Extract just the function body for fairer comparison."""
    # Remove includes and extra whitespace
    lines = []
    for line in code.split('\n'):
        stripped = line.strip()
        if stripped.startswith('#include'):
            continue
        lines.append(line)
    return '\n'.join(lines).strip()


def load_cached_data():
    """Load all cached data from previous evaluation runs."""
    print("Loading cached data...")

    # Load candidates
    candidates_file = resolve_cache_file(
        CACHE_DIR,
        f"candidates_{NUM_SAMPLES}_{NUM_CANDIDATES}",
        ".pkl",
        SEED,
        required=True,
    )
    with open(candidates_file, 'rb') as f:
        samples = pickle.load(f)
    print(f"  Loaded {len(samples)} samples with candidates from {candidates_file.name}")

    # Load compilation results
    compile_file = resolve_cache_file(CACHE_DIR, "phase1_compilation", ".pkl", SEED, required=True)
    with open(compile_file, 'rb') as f:
        compilation_results = pickle.load(f)
    print(f"  Loaded compilation results from {compile_file.name}")

    # Load text metrics
    text_file = resolve_cache_file(CACHE_DIR, "phase2_text_metrics", ".pkl", SEED, required=True)
    with open(text_file, 'rb') as f:
        text_metrics = pickle.load(f)
    print(f"  Loaded text metrics from {text_file.name}")

    # Load MBR metrics
    mbr_file = resolve_cache_file(CACHE_DIR, "phase2_5_mbr", ".pkl", SEED)
    mbr_metrics = {}
    if mbr_file.exists():
        with open(mbr_file, 'rb') as f:
            mbr_metrics = pickle.load(f)
        print(f"  Loaded MBR metrics from {mbr_file.name}")

    # Load UniXcoder metrics
    unixcoder_file = resolve_cache_file(CACHE_DIR, "phase3_unixcoder", ".pkl", SEED, required=True)
    with open(unixcoder_file, 'rb') as f:
        unixcoder_metrics = pickle.load(f)
    print(f"  Loaded UniXcoder metrics from {unixcoder_file.name}")

    # Load execution-guided metrics
    execution_guided_file = resolve_cache_file(CACHE_DIR, "phase3_5_execution_guided", ".pkl", SEED)
    execution_guided_metrics = {}
    if execution_guided_file.exists():
        with open(execution_guided_file, 'rb') as f:
            execution_guided_metrics = pickle.load(f)
        print(f"  Loaded execution-guided metrics from {execution_guided_file.name}")

    # Load perplexity metrics
    perplexity_file = resolve_cache_file(CACHE_DIR, "phase3_perplexity", ".pkl", SEED, required=True)
    with open(perplexity_file, 'rb') as f:
        perplexity_metrics = pickle.load(f)
    print(f"  Loaded perplexity metrics from {perplexity_file.name}")

    # Load test results
    test_file = resolve_cache_file(CACHE_DIR, "phase4_test_results", ".pkl", SEED, required=True)
    with open(test_file, 'rb') as f:
        test_results = pickle.load(f)
    print(f"  Loaded test results from {test_file.name}")

    # Apply cached results to samples
    for sample in samples:
        for i, candidate in enumerate(sample.candidates):
            key = (sample.idx, i)

            # Compilation
            if key in compilation_results:
                candidate.compiles = compilation_results[key]

            # Text metrics
            if key in text_metrics:
                candidate.metrics.update(text_metrics[key])

            # MBR metrics
            if key in mbr_metrics:
                candidate.metrics.update(mbr_metrics[key])

            # UniXcoder metrics
            if key in unixcoder_metrics:
                candidate.metrics.update(unixcoder_metrics[key])

            # Execution-guided metrics
            if key in execution_guided_metrics:
                candidate.metrics.update(execution_guided_metrics[key])

            # Perplexity metrics
            if key in perplexity_metrics:
                candidate.metrics.update(perplexity_metrics[key])

            # Test results
            if key in test_results:
                candidate.passes_tests = test_results[key]

    return samples


def select_candidate(compiling: List[Candidate], method: str) -> Optional[Candidate]:
    """Select a candidate using the specified method."""
    if not compiling:
        return None

    if method == 'random':
        return random.choice(compiling)
    elif method == 'oracle':
        # Return a passing candidate if any, else first
        passing = [c for c in compiling if c.passes_tests]
        return passing[0] if passing else compiling[0]
    elif method == 'ensemble_text':
        def score(c):
            return (c.metrics.get('bigram_sim', 0) * 0.4 +
                    c.metrics.get('trigram_sim', 0) * 0.4 +
                    c.metrics.get('token_f1', 0) * 0.2)
        return max(compiling, key=score)
    elif method == 'ensemble_unixcoder_ft':
        def score(c):
            return (c.metrics.get('unixcoder_finetuned', 0) * 0.5 +
                    c.metrics.get('bigram_sim', 0) * 0.25 +
                    c.metrics.get('trigram_sim', 0) * 0.25)
        return max(compiling, key=score)
    elif method == 'ensemble_perplexity':
        def score(c):
            return (c.metrics.get('neg_perplexity', float('-inf')) * 0.5 +
                    c.metrics.get('bigram_sim', 0) * 0.25 +
                    c.metrics.get('trigram_sim', 0) * 0.25)
        return max(compiling, key=score)
    else:
        # Single metric selection
        return max(compiling, key=lambda c: c.metrics.get(method, float('-inf')))


def evaluate_selection_strategies(samples: List[Sample]):
    """Evaluate all selection strategies with multiple metrics."""
    random.seed(RANDOM_SEED)

    # Define methods to evaluate
    single_metrics = [
        'mbr_consensus',
        'execution_guided',
        'edit_similarity',
        'token_f1',
        'bigram_sim',
        'trigram_sim',
        'ast_node_sim',
        'control_flow_sim',
        'identifier_sim',
        'unixcoder_base',
        'unixcoder_finetuned',
        'neg_perplexity',
    ]

    all_methods = (
        ['oracle', 'random'] +
        single_metrics +
        ['ensemble_text', 'ensemble_unixcoder_ft', 'ensemble_perplexity']
    )

    # Initialize results
    results = {m: SelectionResult() for m in all_methods}

    print("\nEvaluating selection strategies...")
    print("(Computing Levenshtein similarity and CodeBLEU for each selection)")

    for sample in tqdm(samples, desc="Samples"):
        compiling = [c for c in sample.candidates if c.compiles]
        if not compiling:
            continue

        # Get original source (clean it)
        original = extract_function_body(sample.c_func)

        # Evaluate each method
        for method in all_methods:
            results[method].total += 1

            # Select candidate
            selected = select_candidate(compiling, method)
            if selected is None:
                continue

            # Pass@1
            if selected.passes_tests:
                results[method].correct += 1

            # Get decompiled code (clean it)
            decompiled = extract_function_body(selected.code)

            # Levenshtein similarity
            lev_sim = compute_levenshtein_similarity(original, decompiled)
            results[method].levenshtein_sum += lev_sim

            # CodeBLEU
            codebleu = compute_codebleu(original, decompiled)
            results[method].codebleu_sum += codebleu

            results[method].count += 1

    return results


def print_results(results: Dict[str, SelectionResult]):
    """Print formatted results."""
    print("\n" + "=" * 90)
    print("RQ2: SELECTION ALGORITHM EVALUATION")
    print("=" * 90)

    # Compute averages and sort by Pass@1
    summary = []
    for method, data in results.items():
        if data.total == 0:
            continue
        pass_rate = data.correct / data.total * 100
        avg_lev = data.levenshtein_sum / data.count * 100 if data.count > 0 else 0
        avg_codebleu = data.codebleu_sum / data.count * 100 if data.count > 0 else 0
        summary.append({
            'method': method,
            'pass_rate': pass_rate,
            'correct': data.correct,
            'total': data.total,
            'levenshtein': avg_lev,
            'codebleu': avg_codebleu,
        })

    # Sort by pass rate
    summary.sort(key=lambda x: x['pass_rate'], reverse=True)

    print(f"\n{'Method':<25} {'Pass@1':>10} {'Levenshtein':>12} {'CodeBLEU':>12}")
    print("-" * 62)

    for item in summary:
        print(f"{item['method']:<25} {item['pass_rate']:>9.1f}% {item['levenshtein']:>11.1f}% {item['codebleu']:>11.1f}%")

    # Print summary statistics
    print("\n" + "=" * 90)
    print("SUMMARY BY METRIC")
    print("=" * 90)

    # Best by Pass@1
    best_pass = max([s for s in summary if s['method'] != 'oracle'], key=lambda x: x['pass_rate'])
    oracle = next(s for s in summary if s['method'] == 'oracle')
    random_result = next(s for s in summary if s['method'] == 'random')

    print(f"\n--- Pass@1 (Functional Correctness) ---")
    print(f"  Oracle (upper bound):   {oracle['pass_rate']:.1f}%")
    print(f"  Best method:            {best_pass['method']} ({best_pass['pass_rate']:.1f}%)")
    print(f"  Random baseline:        {random_result['pass_rate']:.1f}%")
    print(f"  Improvement over random: +{best_pass['pass_rate'] - random_result['pass_rate']:.1f}pp")

    # Best by Levenshtein
    best_lev = max([s for s in summary if s['method'] != 'oracle'], key=lambda x: x['levenshtein'])
    print(f"\n--- Levenshtein Similarity ---")
    print(f"  Oracle:                 {oracle['levenshtein']:.1f}%")
    print(f"  Best method:            {best_lev['method']} ({best_lev['levenshtein']:.1f}%)")
    print(f"  Random baseline:        {random_result['levenshtein']:.1f}%")
    print(f"  Improvement over random: +{best_lev['levenshtein'] - random_result['levenshtein']:.1f}pp")

    # Best by CodeBLEU
    best_cb = max([s for s in summary if s['method'] != 'oracle'], key=lambda x: x['codebleu'])
    print(f"\n--- CodeBLEU ---")
    print(f"  Oracle:                 {oracle['codebleu']:.1f}%")
    print(f"  Best method:            {best_cb['method']} ({best_cb['codebleu']:.1f}%)")
    print(f"  Random baseline:        {random_result['codebleu']:.1f}%")
    print(f"  Improvement over random: +{best_cb['codebleu'] - random_result['codebleu']:.1f}pp")

    return summary


def load_beam_search_results():
    """Load beam search results for comparison."""
    beam_file = CACHE_DIR / "beam_search_summary.json"
    if beam_file.exists():
        with open(beam_file, 'r') as f:
            return json.load(f)
    return None


def print_beam_search_comparison(beam_results, summary):
    """Print comparison with beam search."""
    if not beam_results:
        return

    print("\n" + "=" * 90)
    print("COMPARISON: SELECTION vs BEAM SEARCH")
    print("=" * 90)

    print(f"\n{'Method':<35} {'Pass@1':>10}")
    print("-" * 48)

    # Selection methods (top 3)
    for item in summary[:3]:
        if item['method'] == 'oracle':
            continue
        print(f"{item['method']:<35} {item['pass_rate']:>9.1f}%")

    print("-" * 48)

    # Random
    random_result = next(s for s in summary if s['method'] == 'random')
    print(f"{'Random selection':<35} {random_result['pass_rate']:>9.1f}%")

    print("-" * 48)

    # Beam search methods
    for beam in beam_results:
        beam_size = beam['beam_size']
        pass_rate = beam['pass_rate']
        label = "Greedy (beam=1)" if beam_size == 1 else f"Beam search (k={beam_size})"
        print(f"{label:<35} {pass_rate:>9.1f}%")

    # Summary
    best_selection = max([s for s in summary if s['method'] not in ['oracle', 'random']],
                         key=lambda x: x['pass_rate'])
    greedy_rate = beam_results[0]['pass_rate']
    print(f"\n  Best selection vs Greedy: +{best_selection['pass_rate'] - greedy_rate:.1f}pp")


def save_results(summary: List[Dict]):
    """Save results to JSON file."""
    output = {
        'config': {
            'num_samples': NUM_SAMPLES,
            'num_candidates': NUM_CANDIDATES,
            'random_seed': RANDOM_SEED,
            'candidate_seed': SEED,
        },
        'results': summary,
        'metrics_description': {
            'pass_rate': 'Percentage of samples where selected candidate passes all tests',
            'levenshtein': 'Average Levenshtein similarity to original source (%)',
            'codebleu': 'Average CodeBLEU score comparing to original source (%)',
        }
    }

    output_file = Path(f"selection_evaluation_results{seed_suffix(SEED)}.json")
    with open(output_file, 'w') as f:
        json.dump(output, f, indent=2)
    print(f"\nResults saved to {output_file}")


def main():
    print("=" * 90)
    print("RQ2: Selection Algorithm Evaluation for LLM4Decompile")
    print("=" * 90)
    print(f"\nConfiguration:")
    print(f"  Samples: {NUM_SAMPLES}")
    print(f"  Candidates per sample: {NUM_CANDIDATES}")
    print(f"  Random seed: {RANDOM_SEED}")
    print(f"  Candidate seed: {SEED}")
    print(f"\nMetrics:")
    print(f"  - Pass@1 (functional correctness)")
    print(f"  - Levenshtein similarity (edit distance to original)")
    print(f"  - CodeBLEU (code-aware BLEU score)")

    # Load data
    samples = load_cached_data()

    # Count statistics
    total_candidates = sum(len(s.candidates) for s in samples)
    compiling_candidates = sum(
        sum(1 for c in s.candidates if c.compiles) for s in samples
    )
    passing_candidates = sum(
        sum(1 for c in s.candidates if c.passes_tests) for s in samples
    )

    print(f"\nData statistics:")
    print(f"  Total candidates: {total_candidates:,}")
    print(f"  Compiling: {compiling_candidates:,} ({compiling_candidates/total_candidates*100:.1f}%)")
    print(f"  Passing tests: {passing_candidates:,} ({passing_candidates/total_candidates*100:.1f}%)")

    # Evaluate selection strategies
    results = evaluate_selection_strategies(samples)
    summary = print_results(results)

    # Load and compare beam search results
    beam_results = load_beam_search_results()
    print_beam_search_comparison(beam_results, summary)

    # Save results
    save_results(summary)


if __name__ == "__main__":
    main()
